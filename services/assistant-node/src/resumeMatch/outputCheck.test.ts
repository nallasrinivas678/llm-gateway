// 8d: the text a person copies at the end must be plain. Whatever the model writes (hidden
// characters, curly quotes, long dashes) and whatever the PDF brought in, the text that comes back
// from start, rewrite, place-bullet and accept has none of it, and no machine marker.
import { describe, expect, it, vi } from "vitest";
import { loadSettings } from "../config.js";
import { createMatchService, type GenerateFn } from "./matchService.js";
import type { MatchStore, NewVersion } from "./matchStore.js";
import { placeBullet } from "./rewrite.js";

const settings = loadSettings().resumeMatch;

// Every character 8a removes, and the typography 8b replaces in lines the model wrote.
const HIDDEN = /[​-‍⁠﻿᠎­‎‏‪-‮⁦-⁩   -   　ﬀ-ﬆ]/;
const FANCY = /[‘’“”…–—−]/;
const MARKERS = /ADDITIONAL EXPERIENCE|\[NEW\]|\[ADDED\]|\(added\)|generated by|AI-generated|<mark|\*\*|<!--/i;

// A resume as a PDF might give it: a soft hyphen, a ligature and a no-break space.
const pdfResume = [
  "Jane Doe - Senior Engineer",
  "Fabrikam - Engineer, 2019-2026",
  "- 7 years building C# services at Fabrikam",
  "- Built ASP.NET Core APIs serving 2M re­quests/day",
  "- Packaged services with Docker",
  "Skills: C#, ASP.NET Core, Docker, PostgreSQL",
].join("\n");
const jobText = "Senior .NET engineer at Contoso. Required: 5+ years C#, ASP.NET Core, Azure, Docker and Kubernetes. Nice to have: React, Terraform. ".repeat(3);

function setup(...answers: unknown[]) {
  const versions: NewVersion[] = [];
  const queue = [...answers];
  const generate = (async () => queue.shift()) as GenerateFn;
  let match: Awaited<ReturnType<MatchStore["getMatch"]>>;
  const store: MatchStore = {
    createMatch: vi.fn(async (m, first) => {
      versions.push(first);
      match = { id: "m1", title: m.title, jobUrl: null, jobText, requirements: m.requirements, targetScore: m.targetScore, createdAt: "t", versions: [{ ...first, createdAt: "t" }] };
      return "m1";
    }),
    getMatch: vi.fn(async () => match),
    listMatches: vi.fn(async () => []),
    addVersion: vi.fn(async (_id, v) => {
      versions.push(v);
    }),
  };
  return { service: createMatchService({ generate, settings, openStore: () => store }), versions };
}

const requirementsAnswer = {
  title: "Senior .NET engineer at Contoso",
  requirements: [
    { text: "5+ years C#", kind: "must" },
    { text: "Azure", kind: "must" },
  ],
};
const assessed = (azure: "met" | "missing") => ({
  results: [
    { requirementId: 1, status: "met", evidence: "7 years building C# services at Fabrikam" },
    { requirementId: 2, status: azure, evidence: azure === "met" ? "Deployed APIs to Azure App Service" : "" },
  ],
});
const azureDetail = { requirementId: 2, detail: "Deployed our APIs to Azure App Service" };

// What a model can write: zero-width space, curly quotes, em dash, ellipsis, no-break space.
const dirtyBullet = "Deployed APIs to Azure​ App Service — “fast”…";

function expectPlain(text: string) {
  expect(text).not.toMatch(HIDDEN);
  expect(text).not.toMatch(MARKERS);
}

describe("output check (8d)", () => {
  it("start: the saved and returned resume has no hidden characters", async () => {
    const { service, versions } = setup(requirementsAnswer, assessed("missing"));
    const view = await service.start({ userId: "u", jwt: "j", resumeText: pdfResume, jobText });
    expectPlain(view.resumeText);
    expectPlain(versions[0]!.resumeText);
    expect(view.resumeText).toContain("ASP.NET Core APIs serving 2M requests/day");
  });

  it("rewrite: lines the model wrote come back plain, and the original lines are unchanged", async () => {
    const { service } = setup(
      requirementsAnswer,
      assessed("missing"),
      { additions: [{ requirementId: 2, skill: "Azure", bullet: dirtyBullet, afterLine: "- Packaged services with Docker" }] },
    );
    await service.start({ userId: "u", jwt: "j", resumeText: pdfResume, jobText });
    const proposal = await service.rewrite("u", "j", "m1", [azureDetail]);
    expect(proposal.proposedText).toContain("Deployed APIs to Azure App Service");
    expectPlain(proposal.proposedText);
    expect(proposal.changes.map((c) => c.bullet ?? "")).toSatisfy((bullets: string[]) => bullets.every((b) => !FANCY.test(b)));
  });

  it("place-bullet: a line the user places is plain, and so is the text around it", () => {
    const placed = placeBullet(pdfResume.replace(/[ ­]/g, ""), "Fabrikam - Engineer, 2019-2026", "Deployed APIs to Azure App Service");
    expectPlain(placed);
    expect(placed.split("\n").filter((l) => l.includes("Azure App Service"))).toHaveLength(1);
  });

  it("accept: pasted or edited text is cleaned before it is saved and returned", async () => {
    const { service, versions } = setup(requirementsAnswer, assessed("missing"), assessed("met"));
    await service.start({ userId: "u", jwt: "j", resumeText: pdfResume, jobText });
    const edited = `${pdfResume}\n- Deployed APIs to Azure​ App Service`;
    const view = await service.accept("u", "j", "m1", { resumeText: edited, confirmed: [azureDetail], baseVersion: 1 });
    expectPlain(view.resumeText);
    expectPlain(versions[1]!.resumeText);
  });

  it("the match view carries the resume text and no other text field the page could copy", async () => {
    const { service } = setup(requirementsAnswer, assessed("missing"));
    const view = await service.start({ userId: "u", jwt: "j", resumeText: pdfResume, jobText });
    // The page copies `resumeText` only; the other strings (title, evidence, requirements) are for display.
    const textFields = Object.entries(view).filter(([, v]) => typeof v === "string").map(([k]) => k);
    expect(textFields.sort()).toEqual(["matchId", "resumeText", "title"]);
  });
});
